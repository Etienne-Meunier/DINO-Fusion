#!/usr/bin/env python3
"""Build `paper_figures.ipynb` from the figure scripts of this folder: `python build_notebook.py`.

Every script splits into `compute()` (loading and computation of the signal, returned as a dict), `plot(computed)`
(`table(computed)` for a table: the figures, or the LaTeX table, without saving) and `main()` (compute, plot, save).
The notebook opens with the standalone `fig_huber` section, then the loading cells (`from common import *`) and the
COMMON computations of common.py, then one section per script of SCRIPTS: its docstring as markdown, a cell importing
the script and showing the helpers its `compute` calls (except those of HIDDEN), the body of `compute` inline, and the
call of its `plot` on the result. Nothing is saved from the notebook.
"""
import ast
import os
import textwrap

import nbformat

HERE = os.path.dirname(os.path.abspath(__file__))
STANDALONE = 'fig_huber'
SCRIPTS = ['fig0_unsconstrained', 'fig0_appendix', 'fig1_density_profile', 'fig2_state', 'fig4_constraint_strenght',
           'table1_score_table', 'table2_moments', 'fig5_aposteriori', 'fig6_amoc', 'fig6_moc_density',
           'fig7_aposteriori_drift', 'fig7_appendix', 'fig8_drift_spatial', 'fig8_appendix', 'fig8_sweep_density_huber']
HIDDEN = {'table2_moments': ['training_moments']}
COMMON = ['sigma0', 'zonal_mean', 'zonal_sections', 'density_error']
INTRO = """# Paper figures with dinostics

Every figure and table of the paper, recomputed with the dinostics package (`Results/a_posteriori/dinostics`). Each section follows one script of this folder: what it loads and computes is shown inline (its `compute` and the helpers it calls), then the plotting function of the script draws the result (`plot(computed)`, `table(computed)` for a table). The figures are saved only by running the scripts themselves (`python <script>.py`, into `figures/` or PAPER_FIGURES). The shared helpers are in `common.py`; the call graph and the pieces dinostics has no routine for are in `CALL_GRAPH.md`. This notebook is generated by `build_notebook.py` from the scripts, edit them rather than the cells."""
LOADING = """## Loading

`from common import *` loads, once:

- `GRID`: the dinostics `NemoExperiment` of the 1° reference run (`domain_cfg_out.nc`, `mesh_mask.nc`, `namelist_cfg` of `1deg_restart`), the T grid of the generated states, its xgcm grid (`GRID.grid`) and its masks; sigma_0 is the TEOS-10 polynomial of `metrics.get_density_at_surface`, the EOS of the training constraint;
- `CHANNEL`: the re-entrant channel latitudes of the analytical `DinoConfiguration`;
- `batch`: the 16 normalized training states of the a posteriori data run (`optimal/data/<timestamp>/states.npy`, described by `DATA_ARGS`), `gens`: the generation of every run of the sweep `PREFIX`, `sources = {"data": batch} | gens`;
- `REFERENCE_DENSITY`: the batch-mean zonal sigma_0 section of the 200-state data batch, written once by `build_reference_density.py` (the only script with a DataLoader), the reference of the fig1 median member;
- `observer`: unnormalizes a batch; `to_dataset(x)` puts it on the T grid of `GRID` as an xarray Dataset.

The a posteriori runs are opened on the `NemoExperiment` of the 1/4° reference run by `aposteriori_experiment(results, files)`, their restarts by `restart_state(exp, path)`."""

SHARED = """## Shared computations

The sigma_0 sections and density error used by several figures, from `common.py`: TEOS-10 density (`metrics.get_density_at_surface`), volume-weighted zonal mean, and the vertical difference of sigma_0 with the xgcm grid of `GRID`."""


def markdown(docstring):
    """Docstring as markdown: the lines of a prose paragraph joined into one, an indented paragraph kept as a code block,
    indented items following prose as a bullet list (an item ends on a line ending with , . ; or :, deeper-indented
    lines continue it)."""
    blocks = []
    for paragraph in docstring.strip().split('\n\n'):
        lines = paragraph.splitlines()
        if all(l.startswith(' ') for l in lines):
            blocks.append(textwrap.indent(textwrap.dedent(paragraph), '    '))
            continue
        groups = []
        for line in lines:
            indented, text = line.startswith(' '), line.strip()
            if groups and groups[-1][0] == indented and not (indented and groups[-1][1][-1] in ',.;:'
                                                              and len(line) - len(line.lstrip()) <= 4):
                groups[-1][1] += ' ' + text
            else:
                groups.append([indented, text])
        parts = []
        for indented, text in groups:
            if parts and not indented:
                parts.append('\n')
            parts.append(f'- {text}\n' if indented else f'{text}\n')
        blocks.append(''.join(parts).strip())
    return '\n\n'.join(blocks)


def function_source(source, f):
    """Source of the top-level function `f`, decorators included."""
    start = min([d.lineno for d in f.decorator_list] + [f.lineno])
    return '\n'.join(source.splitlines()[start - 1:f.end_lineno])


def shown_helpers(tree, compute, hidden):
    """Top-level functions of `tree` that `compute` calls by name, in their order in the script, `hidden` left out."""
    called = {n.func.id for n in ast.walk(compute) if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)}
    return [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name in called and n.name not in hidden
            and n.name not in ('compute', 'plot', 'table', 'main')]


def inline(source, f):
    """Body of the function `f` as top-level code: its parameters bound to their defaults, docstring left out, its final
    `return x` written `computed = x`."""
    lines = source.splitlines()
    first = f.body[1] if ast.get_docstring(f) else f.body[0]
    ret = f.body[-1]
    names = [a.arg for a in f.args.args]
    defaults = [ast.get_source_segment(source, d) for d in f.args.defaults]
    bind = f'{", ".join(names)} = {", ".join(defaults)}\n' if names else ''
    body = lines[first.lineno - 1:ret.lineno - 1]
    head, *rest = lines[ret.lineno - 1:ret.end_lineno]
    body += [head.replace('return ', 'computed = ', 1)] + ['    ' + l for l in rest]
    return bind + textwrap.dedent('\n'.join(body))


def section(name):
    """Cells of the script `name`: its docstring as markdown, `from name import *` with the source of the helpers its
    `compute` calls (HIDDEN left out), the body of `compute` inline, and the call of its `plot` (`table`) on the
    result."""
    with open(f'{HERE}/{name}.py') as f:
        source = f.read()
    tree = ast.parse(source)
    functions = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    compute = functions['compute']
    helpers = shown_helpers(tree, compute, HIDDEN.get(name, ()))
    head = '\n\n\n'.join([f'from {name} import *'] + [function_source(source, h) for h in helpers])
    show = 'table' if 'table' in functions else 'plot'
    return [nbformat.v4.new_markdown_cell(f'## {name}\n\n{markdown(ast.get_docstring(tree))}'),
            nbformat.v4.new_code_cell(head),
            nbformat.v4.new_code_cell(inline(source, compute)),
            nbformat.v4.new_code_cell(f'{show}(computed);')]


def shared():
    """Markdown and code cells with the source of the COMMON functions of common.py."""
    with open(f'{HERE}/common.py') as f:
        source = f.read()
    functions = {n.name: n for n in ast.parse(source).body if isinstance(n, ast.FunctionDef)}
    return [nbformat.v4.new_markdown_cell(SHARED),
            nbformat.v4.new_code_cell('\n\n\n'.join(function_source(source, functions[n]) for n in COMMON))]


def build():
    """Write paper_figures.ipynb next to this file."""
    cells = [nbformat.v4.new_markdown_cell(INTRO), *section(STANDALONE),
             nbformat.v4.new_markdown_cell(LOADING),
             nbformat.v4.new_code_cell('%matplotlib inline\nfrom common import *'),
             nbformat.v4.new_code_cell("print(GRID.name, dict(GRID.namelist['nameos']))\n"
                                       "print({s: tuple(x.shape) for s, x in sources.items()})\n"
                                       "to_dataset(batch[:2])"),
             *shared()]
    for name in SCRIPTS:
        cells += section(name)
    nb = nbformat.v4.new_notebook(cells=cells, metadata={'kernelspec': {'name': 'python3', 'display_name': 'Python 3',
                                                                         'language': 'python'}})
    nbformat.write(nb, f'{HERE}/paper_figures.ipynb')
    print(f'{len(cells)} cells')


if __name__ == '__main__':
    build()
